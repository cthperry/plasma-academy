function choice(id, chapter, type, difficulty, tags, question, choices, explanation, reference) {
  return {
    id,
    chapter,
    type,
    difficulty,
    tags,
    question,
    options: choices.map(([text, correct, why], index) => ({ id: optionIds[index], text, correct, why })),
    explanation,
    reference
  };
}

function numeric(id, chapter, difficulty, tags, question, answer, unit, tolerance, explanation, reference) {
  return { id, chapter, type: "numeric", difficulty, tags, question, answer, unit, tolerance, explanation, reference };
}

