function concept(chapter, tag, reference, imageId, single, multi, graphic, scenarios, tags = []) {
  return { chapter, tag, tags, reference, image: `/assets/svg/l3/${imageId}.svg`, single, multi, graphic, scenarios };
}

function buildQuestions(item, index) {
  const base = index * 5 + 1;
  const id = (offset) => `L3-${String(base + offset).padStart(3, "0")}`;
  return [
    choice(id(0), "single", item, item.single),
    choice(id(1), "multi", item, item.multi),
    { ...choice(id(2), "graphic", item, item.graphic), image: item.image, imageAlt: `${item.reference} 圖形判讀` },
    choice(id(3), "scenario", item, item.scenarios[0]),
    choice(id(4), "scenario", item, item.scenarios[1])
  ];
}

function choice(id, type, item, [question, correctTexts, wrongTexts]) {
  const correct = Array.isArray(correctTexts) ? correctTexts : [correctTexts];
  const wrong = wrongTexts.length ? wrongTexts : ["只看單一 setpoint，不確認任何中介量或副作用"];
  const raw = [...correct.map((text) => ({ text, correct: true })), ...wrong.map((text) => ({ text, correct: false }))];
  const shift = Number(id.slice(-3)) % raw.length;
  const options = [...raw.slice(shift), ...raw.slice(0, shift)].map((option, optionIndex) => ({
    id: String.fromCharCode(65 + optionIndex), text: option.text, correct: option.correct,
    why: option.correct ? `符合 ${item.reference} 的機制、適用條件與證據鏈。` : `這個選項忽略空間位置、中介量或 ${item.reference} 的適用邊界。`
  }));
  return {
    id, chapter: item.chapter, type, difficulty: type === "single" ? 1 : type === "multi" ? 2 : 3,
    tags: [item.tag, ...(item.tags ?? []), type], question, options,
    explanation: `依 ${item.reference}，先辨識現象位置與機制，再用可量測訊號排除替代假說，且同步檢查對策副作用。`, reference: item.reference
  };
}
